import { chromium } from '@playwright/test';
import fs from 'node:fs';
const base='http://127.0.0.1:5173';
fs.mkdirSync('outputs',{recursive:true});
const browser=await chromium.launch({executablePath:'C:/Program Files/Google/Chrome/Application/chrome.exe',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1440,height:1000},deviceScaleFactor:1});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('.world-ready').waitFor();
await page.locator('.world-ready').scrollIntoViewIfNeeded();
await page.waitForTimeout(500);

await page.locator('img').evaluateAll(imgs=>imgs.forEach(i=>i.loading='eager'));
await page.waitForFunction(()=>Array.from(document.images).every(i=>i.complete));
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:'outputs/hero-desktop.png'});
await page.screenshot({path:'outputs/home-desktop.png',fullPage:true});
const homeTitle=await page.title();
const imageFailures=await page.locator('img').evaluateAll(imgs=>imgs.filter(i=>!i.complete||i.naturalWidth===0).map(i=>i.src));
await page.getByRole('tab',{name:'Readiness',exact:true}).click();
const processWorks=await page.locator('#delivery-panel-1').isVisible();
const routeResults=[];
for(const route of ['/services','/services/power','/services/telecom','/services/solar','/services/civil','/approach','/about','/safety','/projects','/projects/site-readiness','/projects/scope-clarity','/privacy','/contact','/admin']){
 const r=await page.request.get(base+route);routeResults.push({route,status:r.status()});
}
await page.goto(base+'/contact?service=solar&type=vendor');
await page.getByRole('button',{name:'Vendor / partnership'}).waitFor();
await page.getByLabel('Project location').fill('Demo City');
await page.getByRole('button',{name:'Continue to contact details'}).click();
await page.getByLabel('Full name').fill('Demo Reviewer');
await page.getByLabel('Company / organisation').fill('Example Infrastructure');
await page.getByLabel('Business phone').fill('+91 9000000000');
await page.getByLabel('Business email').fill('demo@example.com');
await page.getByLabel('Tell us about the work').fill('Demo enquiry to verify storage and the form experience.');
await page.locator('input[name=consent]').check();
const selected=await page.locator('select[name=service]').inputValue();
await page.getByRole('button',{name:'Save demo enquiry'}).click();
await page.getByText('DEMO ENQUIRY SAVED',{exact:true}).waitFor({timeout:15000});
const reference=await page.locator('.form-success code').textContent();
const unauthorized=await page.request.get(base+'/api/admin');
const crossOrigin=await page.request.post(base+'/api/enquiries',{headers:{Origin:'https://untrusted.example'},data:{}});
const invalid=await page.request.post(base+'/api/enquiries',{headers:{Origin:base},data:{name:''}});
await page.setViewportSize({width:390,height:844});
await page.goto(base,{waitUntil:'networkidle'});
await page.locator('.world-ready').waitFor();
await page.waitForTimeout(500);

await page.locator('img').evaluateAll(imgs=>imgs.forEach(i=>i.loading='eager'));
await page.waitForFunction(()=>Array.from(document.images).every(i=>i.complete));
await page.evaluate(()=>window.scrollTo({top:0,behavior:'instant'}));
await page.screenshot({path:'outputs/hero-mobile.png'});
await page.screenshot({path:'outputs/home-mobile.png',fullPage:true});
const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.getByRole('button',{name:'Open menu'}).click();
const mobileMenu=await page.locator('#mobile-nav').isVisible();
await page.locator('#mobile-nav').getByText('Expertise',{exact:false}).click();
await page.waitForURL('**/services');
await page.emulateMedia({reducedMotion:'reduce'});
await page.goto(base+'/contact');
await page.screenshot({path:'outputs/contact-mobile.png',fullPage:true});
const report={homeTitle,imageFailures,processWorks,routeResults,selected,reference,unauthorizedStatus:unauthorized.status(),crossOriginStatus:crossOrigin.status(),invalidStatus:invalid.status(),mobileOverflow:overflow,mobileMenu,errors};
fs.writeFileSync('outputs/verification.json',JSON.stringify(report,null,2));
console.log(JSON.stringify(report,null,2));
await browser.close();
if(errors.length||imageFailures.length||!processWorks||overflow||!mobileMenu||selected!=='solar'||routeResults.some(r=>r.status!==200)||unauthorized.status()!==403||crossOrigin.status()!==403||invalid.status()!==400)process.exitCode=1;
